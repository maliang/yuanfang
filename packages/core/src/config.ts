export async function ensureWorkspace(workspace?: string): Promise<Paths> {
  const paths = resolvePaths(workspace);
  await Promise.all(
    [paths.workspace, paths.dataDir, paths.projectsDir, paths.skillsDir, paths.pluginsDir, paths.logsDir].map(
      (dir) => mkdir(dir, { recursive: true }),
    ),
  );
  if (!existsSync(paths.personaFile)) {
    await writeFile(paths.personaFile, DEFAULT_PERSONA, "utf8");
  } else {
    // Rename the persona generated by the first prototype (远方 -> 元芳).
    try {
      const persona = await readFile(paths.personaFile, "utf8");
      if (persona.startsWith("# 远方 · 系统 Agent")) {
        await writeFile(paths.personaFile, persona.replaceAll("远方", "元芳"), "utf8");
      }
    } catch {
      // A read-only or malformed persona file is not fatal.
    }
  }
  return paths;
}

export async function loadConfig(workspace?: string): Promise<{ config: AppConfig; paths: Paths }> {
  const paths = await ensureWorkspace(workspace);
  const piSettings = await readJson<PiSettings>(paths.piSettingsFile);
  const provider = piSettings?.defaultProvider ?? process.env.YUANFANG_PROVIDER ?? "opencode-go";
  const model = piSettings?.defaultModel ?? process.env.YUANFANG_MODEL ?? "kimi-k3";
  const stored = await readJson<Partial<AppConfig>>(paths.configFile);
  const now = Date.now();
  const config: AppConfig = {
    workspace: paths.workspace,
    agentName: stored?.agentName?.trim().length ? stored.agentName : "元芳",
    projectsDir: stored?.projectsDir ?? paths.projectsDir,
    provider,
    model,
    projectProvider: stored?.projectProvider ?? provider,
    projectModel: stored?.projectModel ?? model,
    roleProvider: stored?.roleProvider ?? provider,
    roleModel: stored?.roleModel ?? model,
    thinkingLevel: stored?.thinkingLevel ?? "medium",
    roleThinkingLevel: stored?.roleThinkingLevel ?? "medium",
    maxTurns: stored?.maxTurns ?? 80,
    maxConcurrentTasks: stored?.maxConcurrentTasks ?? 4,
    notifyLevel: stored?.notifyLevel ?? "all",
    worktreePerTask: stored?.worktreePerTask ?? false,
    dailyTokenBudget: stored?.dailyTokenBudget ?? 0,
    updateFeedUrl:
      stored?.updateFeedUrl ??
      process.env.YUANFANG_UPDATE_URL ??
      "https://github.com/maliang/yuanfang/releases/latest/download",
    createdAt: stored?.createdAt ?? now,
    updatedAt: stored?.updatedAt ?? now,
    ...stored,
  };
  // Never allow a stale workspace path to win.
  config.workspace = paths.workspace;
  config.projectsDir = stored?.projectsDir ?? paths.projectsDir;
  if (stored === undefined) await saveConfig(paths, config);
  return { config, paths };
}

export async function saveConfig(paths: Paths, config: AppConfig): Promise<void> {
  config.updatedAt = Date.now();
  await writeJson(paths.configFile, config);
}

export async function readPersona(paths: Paths): Promise<string> {
  try {
    return await readFile(paths.personaFile, "utf8");
  } catch {
    await writeFile(paths.personaFile, DEFAULT_PERSONA, "utf8");
    return DEFAULT_PERSONA;
  }
}

export async function writePersona(paths: Paths, persona: string): Promise<void> {
  await writeFile(paths.personaFile, persona, "utf8");
}

export { DEFAULT_PERSONA };
